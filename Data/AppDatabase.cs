    // ------------------------- Helpers -------------------------
    private async Task EnsureBaseCategoriesAsync(IEnumerable<string> names)
    {
        var existing = await _conn.Table<Category>().ToListAsync();
        var existingSet = new HashSet<string>(existing.Select(c => c.Name), StringComparer.InvariantCulture);
        foreach (var n in names)
            if (!existingSet.Contains(n))
                await _conn.InsertAsync(new Category { Name = n });
    }

    private async Task<int> EnsureCategoryAsync(string name)
    {
        name = (name ?? "").Trim();
        var cat = await _conn.Table<Category>().Where(c => c.Name == name).FirstOrDefaultAsync();
        if (cat == null)
        {
            cat = new Category { Name = name };
            await _conn.InsertAsync(cat);
        }
        return cat.Id;
    }

    private async Task<GameConfig> EnsureGameConfigAsync()
    {
        var config = await _conn.Table<GameConfig>().FirstOrDefaultAsync();
        if (config == null)
        {
            config = new GameConfig
            {
                Players = 6,
                Spies = 2,
                Minutes = 3,
                CategoryId = null,
                CategoryName = GeneralCategoryName,
                SecretWord = string.Empty,
                SpyIndices = new List<int>(),
                SelectedDifficulty = null,
                CurrentPlayerIndex = 0
            };
            await _conn.InsertAsync(config);
        }
        return config;
    }

    private static DifficultyLevel ParseDifficulty(string fa) => (fa ?? "").Trim() switch
    {
        "آسان" => DifficultyLevel.Easy,
        "متوسط" => DifficultyLevel.Medium,
        "سخت" => DifficultyLevel.Hard,
        _ => DifficultyLevel.Medium
    };

    private sealed class JsonCategoryMap : Dictionary<string, Dictionary<string, string[]>> { }

    // --- کلید یکتا برای چک وجود داشتن: (CategoryId + TextNormalized) ---
    private static string NormalizeKey(string? s)
    {
        s = (s ?? string.Empty).Trim();
        s = s.Replace('ي', 'ی').Replace('ك', 'ک').Replace("\u200c", ""); // نیم‌فاصله
        return s.ToLowerInvariant();
    }
    private static string MakeDbKey(int categoryId, string text) => categoryId + "|" + NormalizeKey(text);

    // ------------------------- Seed از JSON (با Sanitizer) -------------------------
    private async Task<int> SeedFromJsonAsync(string jsonRaw)
    {
        if (string.IsNullOrWhiteSpace(jsonRaw)) return 0;

        // 1) تلاش مستقیم
        var added = await TrySeed(jsonRaw);
        if (added >= 0) return added;

        // 2) تلاش با Sanitizer
        var fixedJson = SanitizeJson(jsonRaw);
        added = await TrySeed(fixedJson);
        if (added >= 0) return added;

        // 3) اگر باز هم نشد، هیچ کاری نکنیم تا اپ بالا بیاید
        return 0;
    }

    private async Task<int> TrySeed(string json)
    {
        JsonCategoryMap? data;
        try
        {
            data = JsonSerializer.Deserialize<JsonCategoryMap>(json);
        }
        catch
        {
            return -1; // نشد
        }
        if (data == null || data.Count == 0) return 0;

        // موجودی فعلی DB
        var allWords = await _conn.Table<WordItem>().ToListAsync();
        var existingKeys = new HashSet<string>(
            allWords.Select(w => MakeDbKey(w.CategoryId, w.Text)),
            StringComparer.InvariantCulture);

        int inserted = 0;
        var toInsert = new List<WordItem>(Math.Min(10000, data.Sum(k => k.Value.Sum(v => v.Value?.Length ?? 0)) + 8));

        foreach (var (categoryName, diffMap) in data)
        {
            if (string.IsNullOrWhiteSpace(categoryName) || diffMap == null) continue;

            var catId = await EnsureCategoryAsync(categoryName);

            foreach (var (diffFa, words) in diffMap)
            {
                var level = ParseDifficulty(diffFa);
                if (words == null) continue;

                foreach (var raw in words)
                {
                    var txt = (raw ?? "").Trim();
                    if (txt.Length == 0 || txt.Length > 30) continue; // محدودیت منطقی برای واژه

                    // معیار وجود داشتن: Category + متن نرمال‌شده
                    var key = MakeDbKey(catId, txt);
                    if (existingKeys.Contains(key))
                    {
                        // قبلاً حداقل یک رکورد با همین متن در این دسته هست → دوباره درج نکن
                        continue;
                    }

                    // درج (حتی اگر همین متن در دسته‌ی دیگر باشد؛ مجاز است)
                    toInsert.Add(new WordItem { CategoryId = catId, Text = txt, Difficulty = level });
                    existingKeys.Add(key);
                    inserted++;
                }
            }
        }

        if (toInsert.Count > 0)
            await _conn.InsertAllAsync(toInsert);

        return inserted;
    }

    /// <summary>
    /// تلاش برای تمیز کردن JSON شبه‌–متن (تعویض نقل‌قول هوشمند، حذف خطوط چتی، و…)
    /// </summary>
    private static string SanitizeJson(string s)
    {
        if (string.IsNullOrEmpty(s)) return s;

        // نقل‌قول‌های هوشمند → استاندارد
        s = s.Replace('“', '"').Replace('”', '"').Replace('‘', '\'').Replace('’', '\'');

        // حذف BOM/کنترل‌های نامرئی
        s = s.Replace("\uFEFF", "").Replace("\u200B", "").Replace("\u200C", "");

        // حذف خطوطی شبیه چت (مثلاً: "Ftme, [8/16/2025 3:31 PM]")
        var lines = s.Split(new[] { "\r\n", "\n" }, System.StringSplitOptions.None)
                     .Where(line => !Regex.IsMatch(line, @"^[A-Za-z]+,\s*\[\d{1,2}/\d{1,2}/\d{2,4}"))
                     .ToList();
        s = string.Join("\n", lines);

        // حذف کاماهای دوتایی احتمالی
        s = Regex.Replace(s, @",\s*,", ",");

        // تلاش برای بستن آرایه/شیء اگر انتها نیمه‌کاره باشد (ملایم)
        // (عمداً محافظه‌کار: تغییری در براکت‌ها نمی‌دهیم تا ساختار اصلی حفظ شود)

        return s;
    }

    // ------------------------- Queries (با ضدتکرار ۵۰۰تایی) -------------------------
    private sealed class TextRow { public string Text { get; set; } = string.Empty; }

    private async Task<HashSet<string>> GetRecentWordKeysAsync(int take)
    {
        if (take <= 0) return new HashSet<string>();
        var rows = await _conn.QueryAsync<TextRow>(
            @"SELECT wi.Text AS Text
              FROM WordHistory wh
              INNER JOIN WordItem wi ON wi.Id = wh.WordItemId
              ORDER BY wh.Id DESC
              LIMIT ?", take);
        return rows.Select(r => NormalizeKey(r.Text)).ToHashSet();
    }

    public Task<List<Category>> GetCategoriesAsync() =>
        _conn.Table<Category>().OrderBy(c => c.Name).ToListAsync();

    public async Task<List<WordItem>> GetWordsByCategoryAsync(int categoryId, DifficultyLevel? difficulty = null, int recentWindow = 500)
    {
        var recentKeys = await GetRecentWordKeysAsync(recentWindow);
        var query = _conn.Table<WordItem>().Where(w => w.CategoryId == categoryId);
        if (difficulty.HasValue) query = query.Where(w => w.Difficulty == difficulty.Value);

        var words = await query.ToListAsync();

        // جلوگیری از تکرار متنی داخل همین دسته + فیلتر ۵۰۰ اخیر
        var filtered = words
            .GroupBy(w => NormalizeKey(w.Text))
            .Where(g => !recentKeys.Contains(g.Key))
            .Select(g => g.First())
            .OrderBy(w => w.Text)
            .ToList();

        return filtered;
    }

    public async Task<List<WordItem>> GetAllWordsAsync(DifficultyLevel? difficulty = null, int recentWindow = 500)
    {
        var recentKeys = await GetRecentWordKeysAsync(recentWindow);
        var query = _conn.Table<WordItem>();
        if (difficulty.HasValue) query = query.Where(w => w.Difficulty == difficulty.Value);

        var words = await query.ToListAsync();

        var filtered = words
            .GroupBy(w => NormalizeKey(w.Text))
            .Where(g => !recentKeys.Contains(g.Key))
            .Select(g => g.First())
            .OrderBy(w => w.Text)
            .ToList();

        return filtered;
    }

