    public async Task RollbackLastRoundAsync()
    {
        // آخرین GameConfig
        var lastCfg = await GetLastConfigAsync();
        if (lastCfg != null)
        {
            await DeleteGameConfigAsync(lastCfg);
        }

        // حذف آخرین WordHistory (مرتبط با آخرین کلمه ثبت‌شده)
        var lastWord = await GetLastWordHistoryAsync();
        if (lastWord != null)
        {
            await DeleteWordHistoryAsync(lastWord);
        }
    }

